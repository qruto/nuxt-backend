// Post-process the TypeDoc markdown so it renders cleanly inside Nuxt Content /
// Docus. TypeDoc emits inter-page links relative to each file and with a `.md`
// extension (`[convex/app](convex/app.md)`). Two problems for Nuxt Content:
//   1. routes are extension-less, so `.md` links 404; and
//   2. the prerender crawler resolves *relative* links against the current URL,
//      and because the folder index route has no trailing slash, `convex/app`
//      resolves to `/api-reference/convex/app` (missing `/reference/`) → fatal
//      crawl errors.
// Fix both by rewriting every internal link to a root-absolute route, resolved
// against the file's own location. External URLs, in-page anchors, and already
// absolute links are left untouched.
import { readdir, readFile, writeFile } from 'node:fs/promises'
import { join, relative, posix, sep } from 'node:path'
import packageJson from '../package.json' with { type: 'json' }

const ROOT = new URL(
  '../website/content/7.api-reference/9.reference/',
  import.meta.url,
).pathname

// The route the `9.reference` folder is served at (Nuxt Content strips the
// numeric `N.` prefixes: `7.api-reference/9.reference` -> `/api-reference/reference`).
const BASE_ROUTE = '/api-reference/reference'

// Any relative link target: skip external (`https://`), root-absolute (`/`),
// pure anchors (`#`), and protocol-ish (`mailto:`) links.
const LINK = /\]\((?!https?:\/\/|\/|#|mailto:)([^)]+)\)/g

// `Defined in:` paths for symbols re-exported from dependencies (convex, the TS
// lib) are emitted as the on-disk location, which under pnpm's default isolated
// linker is the store path: `node_modules/.pnpm/convex@1.42.3_react@19.2.8/
// node_modules/convex/...`. That embeds both the node_modules layout and the
// exact resolved version, so the committed reference drifts — and the ci drift
// gate fails — whenever the linker or any dependency version changes. Collapse
// the store segment back to the plain `node_modules/<pkg>/...` form, which is
// what the path means and is stable across both. Underscores arrive
// markdown-escaped (`node\_modules`), so match either spelling.
const PNPM_STORE = /node(\\?)_modules\/\.pnpm\/[^/]+\/node\\?_modules\//g

// typedoc.json spells the source link as a template rooted at `src/` (git
// detection is off, so the output is the same from a worktree). A symbol that
// lives in a dependency then gets a link that climbs out of that root —
// `blob/main/src/../node_modules/…` — which points at nothing on GitHub. Keep
// the path text, drop the link. Runs before the two rewrites below, which only
// touch the text.
const DEPENDENCY_SOURCE_LINK = /\[([^\]]+)\]\(https:\/\/github\.com\/[^)]*\/blob\/main\/src\/\.\.\/[^)]*\)/g

// Members inherited from the base module are located inside its installed
// declarations: `node_modules/nuxt-convex-module/dist/…/use-auth.d.ts:71` —
// and the line moves with every base-module release. Collapse to the module
// path (no dist segment, extension, or line), the part that means something
// and is stable across bumps. Underscores may arrive markdown-escaped here too.
const BASE_MODULE_SOURCE = /nuxt-convex-module\/(?:dist|src)\/([\w\\./-]+?)(?:\.d)?\.(?:m?ts|js):\d+/g

// The one frontmatter TypeDoc writes (`frontmatterGlobals` in typedoc.json).
// Everything Nuxt Content needs beyond it is derived below.
const TYPEDOC_FRONTMATTER = /^---\nnavigation: true\n---/

// Every page is TypeDoc output. The banner sits after the frontmatter, where
// someone opening the file to "fix a typo" reads it before the first heading —
// and where Nuxt Content, which parses HTML comments to nothing, ignores it.
const BANNER = '<!-- Generated by TypeDoc (pnpm run docs:reference) — do not edit; change the JSDoc in src/ instead. -->'

// TypeDoc emits only `navigation: true` in each page's frontmatter, and Nuxt
// Content does NOT read the H1 — it falls back to the *filename* for `title`
// and leaves `description` empty. That gives a `<title>` of "billing" for both
// `convex/integrations/billing` and `convex/components/backend/billing`, and
// no meta description anywhere. Derive both from what TypeDoc already wrote:
// the H1 is the module path, and the paragraph under it is the module's TSDoc
// summary.
//
// `title` is the full module path, so the page heading and the `<title>` tag
// are unique. The sidebar row is the last segment (`navigation.title`): the
// tree already spells out the folders above it, and `convex/integrations/
// billing` under `convex › integrations` would say everything twice.
const DESCRIPTION_MAX = 160

// Module path → the specifier a consumer imports it by, read from package.json
// `exports` (`convex/integrations/billing` → `nuxt-backend/billing`). TypeDoc
// names a module after its file minus a trailing `/index`; the `.js`-suffixed
// duals of the component entries are skipped so the plain spelling wins. A
// module without a specifier is an auto-imported composable file.
const IMPORT_NAMES = new Map(
  Object.entries(packageJson.exports).flatMap(([subpath, target]) => {
    const file = typeof target === 'string' ? target : target.default
    const module = file?.match(/^\.\/dist\/(.+?)(?:\/index)?\.js$/)?.[1]
    return module && !subpath.endsWith('.js') ? [[module, posix.join(packageJson.name, subpath)]] : []
  }),
)

/** Sidebar icon per module family — the same ones the hand-written pages of each area use. */
function iconFor(module) {
  if (module === 'module') return 'i-lucide-settings'
  if (module.startsWith('runtime/vue/composables/')) return 'i-lucide-function-square'
  if (module.startsWith('runtime/server/')) return 'i-lucide-terminal'
  if (module.startsWith('convex/components/')) return 'i-lucide-box'
  if (module.startsWith('convex/')) return 'i-lucide-server'
  return 'i-lucide-file-code'
}

/** First prose paragraph under the H1, flattened and stripped of markdown. */
function summarize(body) {
  const afterH1 = body.split(/^# .*$/m)[1] ?? ''
  const paragraph = afterH1.trimStart().split(/\n\s*\n/)[0]
  // Tables, lists and headings are not prose — those modules have no summary.
  // An empty paragraph needs no guard: it falls through and flattens to ''.
  if (/^[|\-*#>]/.test(paragraph)) return ''
  return paragraph
    .replace(/\[([^\]]+)\]\([^)]*\)/g, '$1') // links -> their text
    .replace(/[`*_]/g, '')
    .replace(/\s+/g, ' ')
    .trim()
}

function describe(module, body) {
  const summary = summarize(body)
  if (!summary) {
    const importName = IMPORT_NAMES.get(module)
    return importName ? `API reference for ${importName}.` : `API reference for ${module}, auto-imported in the app.`
  }
  if (summary.length <= DESCRIPTION_MAX) return summary
  return `${summary.slice(0, summary.lastIndexOf(' ', DESCRIPTION_MAX - 1))}…`
}

function frontmatter(module, body) {
  return [
    '---',
    `title: ${JSON.stringify(module)}`,
    `description: ${JSON.stringify(describe(module, body))}`,
    'navigation:',
    `  title: ${JSON.stringify(module.slice(module.lastIndexOf('/') + 1))}`,
    `  icon: ${iconFor(module)}`,
    '---',
    BANNER,
  ].join('\n')
}

async function* walk(dir) {
  for (const entry of await readdir(dir, { withFileTypes: true })) {
    const path = join(dir, entry.name)
    if (entry.isDirectory()) yield* walk(path)
    else if (entry.name.endsWith('.md')) yield path
  }
}

let touched = 0
for await (const file of walk(ROOT)) {
  const src = await readFile(file, 'utf8')
  const relPath = relative(ROOT, file).split(sep).join('/')
  // Route directory of THIS file, e.g. `convex/app.md` -> `/api-reference/reference/convex`.
  const relDir = posix.dirname(relPath)
  const linkBase = relDir === '.' ? BASE_ROUTE : posix.join(BASE_ROUTE, relDir)

  let out = src
    .replace(DEPENDENCY_SOURCE_LINK, '$1')
    .replace(PNPM_STORE, 'node$1_modules/')
    .replace(BASE_MODULE_SOURCE, 'nuxt-convex-module/$1')
    .replace(LINK, (_match, target) => {
      const hash = target.indexOf('#')
      const path = hash === -1 ? target : target.slice(0, hash)
      const anchor = hash === -1 ? '' : target.slice(hash)
      const clean = path.replace(/\.md$/, '')
      if (!clean) return `](${anchor})` // safety: anchor-only
      const abs = posix.normalize(posix.join(linkBase, clean))
      return `](${abs}${anchor})`
    })

  // `index.md` gets its own (hand-written) meta below.
  if (relPath !== 'index.md') {
    const module = out.match(/^# (.+)$/m)?.[1]?.trim() ?? relPath.replace(/\.md$/, '')
    out = out.replace(TYPEDOC_FRONTMATTER, () => frontmatter(module, out))
  }

  if (out !== src) {
    await writeFile(file, out)
    touched++
  }
}

// TypeDoc wipes the output dir on every run (`cleanOutputDir`), so the Docus
// folder-navigation file has to be (re)written here rather than committed by hand.
await writeFile(
  join(ROOT, '.navigation.yml'),
  'title: Modules\nicon: i-lucide-boxes\n',
)

// Give the generated landing page a human title/description instead of the bare
// package name TypeDoc emits as the H1.
const indexPath = join(ROOT, 'index.md')
const index = await readFile(indexPath, 'utf8')
await writeFile(
  indexPath,
  index
    .replace(TYPEDOC_FRONTMATTER, [
      '---',
      'title: Modules',
      'description: Auto-generated TypeScript API reference for every public nuxt-backend module.',
      'navigation:',
      '  icon: i-lucide-boxes',
      '---',
      BANNER,
    ].join('\n'))
    .replace(/^# nuxt-backend$/m, '# API Modules'),
)

console.log(`typedoc-postprocess: cleaned links + wrote frontmatter in ${touched} file(s); wrote nav + index meta`)
