// ── Markdown ─────────────────────────────────────────────────────────────────

const code = text => `\`${text}\``

/** A Markdown table. */
function table(head, rows) {
  return [`| ${head.join(' | ')} |`, `|${head.map(() => '---').join('|')}|`, ...rows.map(row => `| ${row.join(' | ')} |`)].join('\n')
}

/** Backticks around each `<Component>` a docs description names, so Markdown keeps the tag. */
const tagsAsCode = text => text.replace(/(`[^`]*`)|<([A-Z]\w*)>/g, (match, quoted, tag) => quoted ?? code(`<${tag}>`))

/** The composables or import path a docs `api` link names: `/docs/reference/api/use-credits` → `useCredits()`. */
function apiNames(api, data) {
  const slug = /\/docs\/reference\/api\/([\w-]+)$/.exec(api ?? '')?.[1]
  if (!slug) return []
  const composables = data.composables.filter(item => item.file.endsWith(`/${slug}.ts`)).map(item => code(`${item.name}()`))
  if (composables.length > 0) return composables
  const slugOf = path => path === 'nuxt-backend' ? 'module' : path.slice('nuxt-backend/'.length).replace(/[/.]/g, '-')
  const entry = data.entries.find(item => slugOf(item.path) === slug)
  return entry ? [code(entry.path)] : []
}

/**
 * What a docs page has an app reach for, its primary API first: the
 * composables or import path its `api` link names; else the composables or
 * components registered from its `source`, or that file's import path; else
 * the functions an import path re-exports from it.
 */
function reachFor(page, data) {
  const primary = apiNames(page.api, data)
  if (primary.length > 0 || !page.source) return primary
  const registered = [
    ...data.composables.filter(item => item.file === page.source).map(item => code(`${item.name}()`)),
    ...data.components.filter(item => item.file === page.source).map(item => code(`<${item.name}>`)),
  ]
  if (registered.length > 0) return registered
  const entry = data.entries.find(item => item.source === page.source)
  if (entry) return [code(entry.path)]
  const reexported = data.entries.flatMap(item => item.exports.filter(name => name.origin === page.source && !name.type).map(name => ({ name, path: item.path })))
    .sort((a, b) => Number(b.name.fn) - Number(a.name.fn))
  return [...new Set(reexported.map(({ name, path }) => `${code(name.fn ? `${name.name}()` : name.name)} from ${code(path)}`))].slice(0, 2)
}

/** Whether a docs `route` sits at or under `prefix`. */
const under = (route, prefix) => route === prefix || route.startsWith(`${prefix}/`)

/**
 * The skill a docs route belongs to: the one whose `docs` holds the longest
 * prefix of it, so `/docs/ship/releases/upgrade` goes to the upgrade skill
 * and the rest of `/docs/ship` to the ship skill. Undefined when none does.
 */
export function skillOf(route) {
  let best
  for (const skill of AGENT_SKILLS) {
    for (const prefix of skill.docs) {
      if (under(route, prefix) && (!best || prefix.length > best.prefix.length)) best = { skill, prefix }
    }
  }
  return best?.skill
}

/**
 * Each skill's tasks: its how-to pages, by docs tab and in sidebar order,
 * each with what it reaches for. A how-to page no skill claims stops the
 * generator, since no agent would be routed to it. A page marked
 * `agents: false` is about this repository's own tooling, which an app's
 * agent cannot use: no skill lists it. Nor does any list a planned page
 * (`status: planned`): what it describes is not built yet, and a skill
 * ships to agents writing code against the version installed.
 */
function skillTasks(data) {
  const pages = data.docs.filter(page => page.kind === 'how-to' && page.agents !== 'false' && !isPlanned(page))
  const unowned = pages.filter(page => !skillOf(page.route)).map(page => page.route)
  if (unowned.length > 0) throw new Error(`agent-guidance: no skill covers ${unowned.join(', ')}: add its route to a skill's \`docs\` in src/guidance/skills.ts`)
  return new Map(AGENT_SKILLS.map(skill => [skill.name, DOCS_TABS.map(tab => ({
    tab,
    pages: pages
      .filter(page => skillOf(page.route) === skill && under(page.route, tab.path))
      .map(page => ({ ...page, names: reachFor(page, data) })),
  })).filter(group => group.pages.length > 0)]))
}

/**
 * The core's `tasks` block: its few how-to pages as one line of links, since
 * agents load the core with every task and its budget is the tightest.
 */
function compactTasksBlock(groups) {
  return `${groups.flatMap(group => group.pages).map(page => `[${page.title}](${SITE}${page.route})`).join(', ')}.`
}

/** A skill's `tasks` block: one line per how-to page, under its tab's name when the skill spans several. */
function tasksBlock(groups) {
  const lines = pages => pages.map(page => `- [${page.title}](${SITE}${page.route}): ${tagsAsCode(page.description ?? '')}${page.names.length > 0 ? ` Reach for ${page.names.join(', ')}.` : ''}`).join('\n')
  if (groups.length === 1) return lines(groups[0].pages)
  return groups.map(({ tab, pages }) => `**${tab.title}**\n\n${lines(pages)}`).join('\n\n')
}

/** The core's router: one line per task skill, with what it covers, its task count and its key names. */
function routerBlock(tasks) {
  return TASK_SKILLS.map((skill) => {
    const pages = tasks.get(skill.name).flatMap(group => group.pages)
    const names = [...new Set(pages.flatMap(page => page.names.map(name => name.split(' from ')[0])))].slice(0, 3)
    const count = `${pages.length} ${pages.length === 1 ? 'task' : 'tasks'}`
    return `- ${code(skill.name)}: ${skill.covers}. ${count}${names.length > 0 ? `; reach for ${names.join(', ')}` : ''}.`
  }).join('\n')
}

/** A name as code writes it, without the `<>` of a tag or the `()` of a call. */
export const bareName = text => text.replace(/^<(\w+)>$/, '$1').replace(/\(\)$/, '')

/**
 * Every name an app can write: the import paths' exports, everything the
 * module and the base module auto-import, and what the files behind the
 * auto-imports export beside them (`UseAuthReturn`).
 */
export function knownNames(data) {
  const files = [...new Set([...data.composables, ...data.components].map(item => item.file))]
  return new Set([
    ...data.entries.flatMap(entry => entry.exports.map(item => item.name)),
    ...files.flatMap(file => exportsOf(file).map(item => item.name)),
    ...data.composables.map(item => item.name),
    ...data.components.map(item => item.name),
    ...data.aliases,
    ...data.server,
    ...Object.values(data.base).flat(),
  ])
}

/**
 * The rename map's plain renames, one public name for another: what 0.1
 * called each one. A plain rename whose new name the package does not have
 * stops the generator, since it would send an agent to a name that isn't
 * there: mark an option or a field `reshaped`, or spell it with its call.
 */
export function renamedNames(data) {
  const plain = /^(?:<\w+>|[a-z_]\w*(?:\(\))?)$/i
  const known = knownNames(data)
  const renamed = RENAMES.filter(entry => entry.change === 'renamed' && plain.test(entry.from) && entry.to && plain.test(entry.to))
  const unknown = renamed.filter(entry => !known.has(bareName(entry.to)))
  if (unknown.length > 0) throw new Error(`agent-guidance: a plain rename must lead to a public name, and ${unknown.map(entry => `${entry.from} → ${entry.to}`).join(', ')} does not`)
  return renamed.map(entry => ({ wrong: entry.from, right: entry.to, note: entry.note }))
}

/** SKILL.md's wrong-name list: the guesses, one line per kind. */
function wrongNamesBlock() {
  // The function names are in api.md, beside the scaffold's function contract.
  const KINDS = { composable: 'Composables', component: 'Components', env: 'Env', command: 'Commands (`npx nuxt-backend …`)', import: 'Imports' }
  return Object.entries(KINDS).map(([kind, title]) => {
    // Commands drop the shared `npx nuxt-backend`, which the title names once.
    const bare = text => kind === 'command' ? text.replace('npx nuxt-backend ', '') : text
    const pairs = WRONG_NAMES.filter(entry => entry.kind === kind).map(entry => `${code(bare(entry.wrong))} → ${code(bare(entry.right))}${entry.note ? ` (${entry.note})` : ''}`)
    return `- **${title}:** ${pairs.join('; ')}.`
  }).join('\n')
}

/**
 * SKILL.md's API at a glance: each import path with its main functions.
 * The auto-imports are named where SKILL.md uses them, and
 * references/api.md lists everything.
 */
function apiBlock(data) {
  const primary = (entry) => {
    const values = entry.exports.filter(item => !item.type && item.name !== 'default')
    const own = values.filter(item => item.fn && item.origin.startsWith('src/'))
    return (own.length > 0 ? own : values).slice(0, 2).map(item => item.name)
  }
  return data.entries.filter(entry => !entry.typesOnly).map((entry) => {
    const named = primary(entry)
    return `- ${code(entry.path)}${named.length > 0 ? `: ${named.map(code).join(', ')}` : ''}`
  }).join('\n')
}

/** What to say of an export without a doc comment of its own. */
function fallbackDoc(entry, item) {
  if (!item.origin.startsWith('src/')) return `Re-exported from ${code(item.origin)}.`
  if (item.name === 'default' && entry.path === 'nuxt-backend') return 'The Nuxt module: list `\'nuxt-backend\'` in `modules`.'
  return item.name === 'default' ? 'The default export.' : ''
}

/** An API table row: a name and its doc comment's first sentence. */
const describeRow = (name, doc) => `| ${code(name)} | ${summary(doc)} |`

/** One import path's section of an API reference: its values with their docs, then its types. */
function entrySection(entry) {
  if (entry.typesOnly) return `### ${code(entry.path)}\n\nTypes only: the generated API of the \`backend\` component.`
  const valueRows = entry.exports.filter(item => !item.type).map(item => describeRow(item.fn ? `${item.name}()` : item.name, item.doc || fallbackDoc(entry, item)))
  const types = entry.exports.filter(item => item.type).map(item => code(item.name))
  return [
    `### ${code(entry.path)}`,
    valueRows.length > 0 ? ['| Export | What it is |', '|---|---|', ...valueRows].join('\n') : '',
    types.length > 0 ? `Types: ${types.join(', ')}.` : '',
  ].filter(Boolean).join('\n\n')
}

/** One CLI command's section: what it does, its flags and its `--json`. */
function commandSection(item) {
  const flags = item.flags.map(flag => `- ${code(flag.flag)}: ${flag.description}`).join('\n')
  return [`### ${code(`npx nuxt-backend ${item.path}`)}`, `${item.description}.`, flags, item.contract ? `\`--json\`: ${item.contract.json}.` : ''].filter(Boolean).join('\n\n')
}

const composablesTable = list => table(['Composable', 'What it does'], list.map(item => [code(`${item.name}()`), summary(item.doc)]))
const componentsTable = list => table(['Component', 'What it renders'], list.map(item => [code(`<${item.name}>`), summary(item.doc)]))
const findingsTable = list => table(['Id', 'Capability', 'Checks'], list.map(item => [code(item.id), item.capability, item.title]))
const envTable = list => table(['Name', 'Capability', 'Read on', 'Tier', 'Without it'], list.map(entry => [code(entry.name), capabilityOfEnv(entry.name) ?? '', entry.side, envTier(entry), entry.without.replaceAll('|', '\\|')]))
const contractList = modules => modules.map(([module, names]) => `- ${code(`backend/${module}.ts`)}: ${names.map(code).join(', ')}`).join('\n')

/**
 * The route middleware lines: the named middleware a page lists in
 * `definePageMeta({ middleware })`, and the global page guard, which a page
 * never names (Nuxt has no named entry for a global middleware) and asks for
 * with its `auth` rules instead.
 */
function routeMiddlewareLines(data) {
  const named = data.middleware.filter(name => !data.globalMiddleware.includes(name))
  const lines = [`- Route middleware: ${named.map(name => code(`definePageMeta({ middleware: '${name}' })`)).join(', ')} sends a signed-out visitor to sign in.`]
  if (data.globalMiddleware.length) {
    lines.push(`- The page guard (${data.globalMiddleware.map(code).join(', ')}, global, so a page never names it in \`middleware\`): ${code(`definePageMeta({ auth: { ${data.pageAccessRules.join(', ')} } })`)} opens a page only to a signed-in person who passes every rule given; a signed-out visitor goes to sign in, and a signed-in one who fails gets a 403 whose \`error.data.reason\` names the rule.`)
  }
  return lines.join('\n')
}

