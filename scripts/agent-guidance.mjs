/** Whether `name`, exported from `file`, is a function: a declaration, or a `const` bound to an arrow or function expression. */
function isFunction(file, name) {
  const statement = declarationOf(file, name)?.statement
  if (!statement) return false
  if (ts.isFunctionDeclaration(statement)) return true
  if (!ts.isVariableStatement(statement)) return false
  const init = statement.declarationList.declarations.find(item => item.name.getText() === name)?.initializer
  return Boolean(init && (ts.isArrowFunction(init) || ts.isFunctionExpression(init)))
}

/** The doc of `export default name`: the declaration of `name`, since the statement itself has none. */
function defaultDoc(file) {
  const statement = sourceOf(file).statements.find(ts.isExportAssignment)
  return statement && ts.isIdentifier(statement.expression) ? docOf(file, statement.expression.text) : ''
}

/** An import path's exports, each marked `fn` when it is a function. */
function entryExports(entry) {
  if (entry.typesOnly) return []
  return exportsOf(entry.source).map(item => ({
    ...item,
    doc: item.doc || (item.name === 'default' ? defaultDoc(entry.source) : ''),
    fn: !item.type && isFunction(entry.source, item.name),
  }))
}

/**
 * A doc comment's first paragraph as one Markdown line, safe in a table
 * cell: code blocks dropped, links reduced to their words, pipes escaped.
 */
function oneLine(doc) {
  return doc.replace(/```[\s\S]*?```/g, '').trim().split(/\n\s*\n/)[0]
    .replace(/\[([^\]]+)\]\([^)]+\)/g, '$1')
    .replace(/\s+/g, ' ')
    .trim()
    .replaceAll('|', '\\|')
}

/** The first sentence of a doc comment, as one table-safe Markdown line. */
const summary = doc => firstSentence(oneLine(doc))

// ── The registries ───────────────────────────────────────────────────────────

/** Every command of the CLI by its path (`env push`), with its flags. */
function cliCommands(command = main, path = []) {
  const subCommands = command.subCommands ?? {}
  if (Object.keys(subCommands).length === 0) {
    const description = (command.meta?.description ?? '').replace(/\s*\[[^\]]*\]$/, '')
    const flags = Object.entries(command.args ?? {}).flatMap(([name, def]) => {
      if (def.type === 'positional') return [{ flag: `<${name}>`, description: def.description ?? '' }]
      // A boolean that defaults on is set by its `--no-` form; one with no default takes both.
      const forms = def.type !== 'boolean' ? [`--${name}`] : def.default === true ? [`--no-${name}`] : def.default === false ? [`--${name}`] : [`--${name}`, `--no-${name}`]
      return forms.map(flag => ({ flag, description: def.description ?? '' }))
    })
    const id = path.join(' ')
    return [{ path: id, description, flags, contract: COMMAND_CONTRACTS.get(id) }]
  }
  return Object.entries(subCommands).flatMap(([name, sub]) => cliCommands(sub, [...path, name]))
}

/** Each error code's sentence, from the list in the doc comment over BACKEND_ERRORS. */
function errorMeanings() {
  const text = read('src/convex/errors.ts')
  const doc = text.slice(text.lastIndexOf('/**', text.indexOf('export const BACKEND_ERRORS')), text.indexOf('export const BACKEND_ERRORS'))
  const flat = doc.split('\n').map(line => line.replace(/^\s*\*\/?\s?/, '')).join('\n')
  return Object.fromEntries([...flat.matchAll(/^- `(\w+)` — ([\s\S]*?)(?=\n- `|\n\s*$)/gm)].map(([, code, meaning]) => [code, oneLine(meaning).replace(/^\w/, letter => letter.toUpperCase())]))
}

/** The route a docs file is served at: `docs/04.build/2.billing/6.credits/index.md` → `/docs/build/billing/credits`. */
function docsRoute(file) {
  const segments = file.slice('website/content/'.length).replace(/\.md$/, '').split('/').map(segment => segment.replace(/^\d+\./, ''))
  if (segments.at(-1) === 'index') segments.pop()
  return `/${segments.join('/')}`
}

/** Every hand-written docs page, in sidebar order. */
function docsPages() {
  const walk = dir => readdirSync(join(root, dir)).sort((a, b) => a.localeCompare(b, 'en', { numeric: true })).flatMap((entry) => {
    const path = `${dir}/${entry}`
    if (statSync(join(root, path)).isDirectory()) return path.endsWith('/10.api') ? [] : walk(path)
    return path.endsWith('.md') ? [path] : []
  })
  return walk('website/content/docs').map(file => ({ file, route: docsRoute(file), ...frontmatter(read(file)) }))
}

// ── The manifest ─────────────────────────────────────────────────────────────

/** The rules `definePageMeta({ auth })` takes: the keys of `PageAccessRules`. */
function pageAccessRuleKeys() {
  const found = declarationOf('src/runtime/vue/utils/access-rules.ts', 'PageAccessRules')
  if (!found || !ts.isInterfaceDeclaration(found.statement)) throw new Error('agent-guidance: found no PageAccessRules interface in src/runtime/vue/utils/access-rules.ts')
  return found.statement.members.map(member => member.name.getText())
}

/** Everything the generator renders, read once. */
export function collect() {
  const registry = moduleRegistry()
  const entries = entrypoints().map(entry => ({ ...entry, exports: entryExports(entry) }))
  const docOf = (file, name) => {
    const found = exportsOf(file).find(item => item.name === name)
    return found?.doc || (found && !found.origin.startsWith('src/') ? `The base module's, from \`${found.origin}\`, under a neutral name.` : '')
  }
  const pageDocs = Object.fromEntries(readPages().map(page => [page.key, page.doc]))
  return {
    entries,
    composables: registry.composables.map(item => ({ ...item, doc: docOf(item.file, item.name) })),
    components: registry.components.map(item => ({ ...item, doc: docOf(item.file, item.exported) })),
    aliases: registry.aliases.map(alias => alias.name),
    parts: registry.parts,
    appAliases: registry.appAliases,
    server: registry.server,
    middleware: registry.middleware,
    globalMiddleware: registry.globalMiddleware,
    pageAccessRules: pageAccessRuleKeys(),
    base: baseModuleSurface(),
    pages: BACKEND_PAGE_DEFS.map(page => ({ key: page.key, path: page.defaultPath, doc: pageDocs[page.key] ?? '' })),
    cli: cliCommands(),
    errors: Object.entries(BACKEND_ERRORS).map(([code, entry]) => ({ code, status: entry.status })),
    errorMeanings: errorMeanings(),
    findings: Object.entries(FINDINGS).map(([id, entry]) => ({ id, capability: entry.capability, group: entry.group, title: entry.title })),
    capabilities: CAPABILITY_NAMES.map(name => ({ name, title: CAPABILITIES[name].title, env: [...CAPABILITIES[name].env] })),
    env: Object.entries(BACKEND_ENV).map(([name, entry]) => ({ name, ...entry })),
    functions: REQUIRED_FUNCTION_EXPORTS,
    docs: docsPages(),
  }
}

/** The tier an env name sits in. */
const envTier = entry => entry.required ? 'required' : entry.devOnly ? 'dev-only' : entry.tooling ? 'tooling' : 'optional'

/** The public-surface manifest, as surface.json holds it. */
export function surfaceManifest(data) {
  const names = list => [...new Set(list)].sort()
  return {
    $comment: `The public surface of the installed nuxt-backend. ${GENERATED_BY}`,
    entrypoints: Object.fromEntries(data.entries.map(entry => [entry.path, {
      values: names(entry.exports.filter(item => !item.type).map(item => item.name)),
      types: names(entry.exports.filter(item => item.type).map(item => item.name)),
    }])),
    autoImports: {
      composables: names(data.composables.map(item => item.name)),
      components: names([...data.components.map(item => item.name), ...data.aliases]),
      parts: names(data.parts.map(item => item.name)),
      server: names(data.server),
      middleware: names(data.middleware),
      baseModule: Object.fromEntries(Object.entries(data.base).map(([kind, list]) => [kind, names(list)])),
    },
    aliases: data.appAliases,
    pages: Object.fromEntries(data.pages.map(page => [page.key, page.path])),
    cli: Object.fromEntries(data.cli.map(command => [command.path, command.flags.map(item => item.flag)])),
    errors: data.errors.map(item => item.code),
    findings: Object.fromEntries(data.findings.map(item => [item.id, item.capability])),
    capabilities: Object.fromEntries(data.capabilities.map(capability => [capability.name, capability.env])),
    env: Object.fromEntries(data.env.map(entry => [entry.name, envTier(entry)])),
    functions: data.functions,
  }
}

