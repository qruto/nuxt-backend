#!/usr/bin/env node
/**
 * The agent guidance that ships in the package, generated from the code: the
 * public-surface manifest and the rename map, and from them the parts of the
 * skills that list names. Every file lands under skills/, which `files` in
 * package.json ships, so an app's agent reads guidance for exactly the
 * version it has installed. src/guidance/skills.ts names the skills: the
 * core, `nuxt-backend`, and the task skills it routes to.
 *
 * In the core, skills/nuxt-backend/:
 * - `references/surface.json`: every public name, by kind: the import paths
 *   and what each exports, the auto-imports, the pages, the CLI, the error
 *   codes, the doctor findings, the env and the scaffold's function contract.
 * - `references/renames.json`: the rename map (src/guidance/renames.ts),
 *   with a link into the Upgrade page per entry.
 * - `references/api.md`: the manifest with each name's doc comment.
 * - In `SKILL.md`, the blocks between `<!-- generated:<name> -->` and
 *   `<!-- /generated:<name> -->`: the router to the task skills, its own
 *   tasks, the wrong-name list (src/guidance/wrong-names.ts plus the rename
 *   map's plain renames) and the API at a glance.
 *
 * In each task skill, skills/nuxt-backend-<task>/:
 * - In `SKILL.md`, the `tasks` block: the how-to pages under the skill's
 *   docs routes, each with what the app reaches for (from the pages'
 *   `api` and `source`).
 * - `references/api.md`: the names the skill owns, with their doc comments.
 * - In the upgrade skill, `references/upgrade.md`: the rename map, by
 *   Upgrade page section.
 *
 * The prose around the blocks is written by hand.
 *
 * Nothing here names the version: the files sit beside the package.json
 * that does, and a release bumps only that.
 *
 *   pnpm agents:generate                    write everything (part of `pnpm generate`)
 *   pnpm agents:generate --check            fail when a file is stale
 */
