/**
 * The skill a doctor finding belongs to: the one whose `findings` names its
 * id, else the one that names its group (a file of src/findings/).
 */
export function findingSkill(item) {
  return AGENT_SKILLS.find(skill => skill.findings?.includes(item.id)) ?? AGENT_SKILLS.find(skill => skill.findings?.includes(item.group))
}

/**
 * What a skill owns, looked up in the data: each name the registry lists,
 * in its order. A name the package does not have stops the generator.
 */
function ownedBy(skill, data) {
  const pick = (list, names, key) => (names ?? []).map((name) => {
    const found = list.find(item => (key ? item[key] : item) === name)
    if (!found) throw new Error(`agent-guidance: src/guidance/skills.ts gives ${skill.name} ${name}, which the package does not have`)
    return found
  })
  const findings = data.findings.filter(item => findingSkill(item) === skill)
  const findingIds = new Set(findings.map(item => item.id))
  return {
    composables: pick(data.composables, skill.composables, 'name'),
    components: pick(data.components, skill.components, 'name'),
    server: pick(data.server, skill.server),
    entries: pick(data.entries, skill.entrypoints, 'path'),
    commands: pick(data.cli, skill.commands, 'path'),
    findings,
    // A variable belongs where a finding about it does.
    env: data.env.filter(entry => entry.findings?.some(id => findingIds.has(id))),
    functions: pick(Object.keys(data.functions), skill.functions).map(module => [module, data.functions[module]]),
  }
}

/** Whether a skill owns any public name, and so gets a references/api.md of its own. */
const ownsNames = skill => [skill.entrypoints, skill.composables, skill.components, skill.server, skill.commands, skill.findings, skill.functions].some(list => (list?.length ?? 0) > 0)

/** A task skill's references/api.md: the names it owns, with their doc comments. */
function skillApiReference(skill, data) {
  const owned = ownedBy(skill, data)
  const sections = [
    owned.composables.length > 0 && `## Auto-imported composables\n\n${composablesTable(owned.composables)}`,
    owned.components.length > 0 && `## Components\n\n${componentsTable(owned.components)}`,
    owned.server.length > 0 && `## Server\n\nNitro auto-imports, in server code: ${owned.server.map(code).join(', ')}.`,
    owned.entries.length > 0 && `## Import paths\n\n${owned.entries.map(entrySection).join('\n\n')}`,
    owned.commands.length > 0 && `## CLI\n\n${owned.commands.map(commandSection).join('\n\n')}`,
    owned.findings.length > 0 && `## Doctor findings\n\n\`npx nuxt-backend doctor --json\` reports these ids, each with a \`docsUrl\` that explains it.\n\n${findingsTable(owned.findings)}`,
    owned.env.length > 0 && `## Environment\n\n${envTable(owned.env)}`,
    owned.functions.length > 0 && `## The scaffold's function contract\n\nThe composables call these functions by name; keep them exported from the scaffolded files.\n\n${contractList(owned.functions)}`,
  ].filter(Boolean)
  return `<!-- ${GENERATED_BY} -->

# ${skill.name}: the API

The public names of ${skill.covers}, each with the first sentence of its doc comment.

The file ships inside the package, so it describes exactly the version in \`node_modules\`. The
core skill, \`${CORE_SKILL.name}\`, lists every public name in its own \`references/api.md\`.

${sections.join('\n\n')}
`
}

/** The upgrade skill's references/upgrade.md: the rename map, by Upgrade page section. */
function upgradeReference(data) {
  const sections = [...new Set(RENAMES.map(entry => entry.section))]
  const cell = text => text === null ? '—' : code(text)
  const blocks = sections.map((section) => {
    const rows = RENAMES.filter(entry => entry.section === section)
      .map(entry => [cell(entry.from), cell(entry.to), entry.change, entry.note ?? ''])
    return `## [${section}](${sectionUrl(section)})\n\n${table(['Was', 'Now', 'Change', 'Note'], rows)}`
  })
  return `<!-- ${GENERATED_BY} -->

# Upgrading: renamed and removed names

The names a release renamed, reshaped or removed, under the Upgrade page section that explains
each, newest first: every composable, component, factory, type and constant the page lists as
gone, and the calls and options whose shape changed. When code written for an earlier version
fails on a name, find it in the **Was** column and write what **Now** says; the section's link
has the reasons and every step. The core skill's \`references/renames.json\`, in
\`${CORE_SKILL.name}\`, holds the same entries as data.

- **renamed**: the same thing under a new name.
- **reshaped**: the same name, called or read differently.
- **removed**: gone. **Now** names what to use instead; a — means nothing replaces it.

\`npx nuxt-backend upgrade\` rewrites none of this: make each edit in the app's code yourself.
After it, run \`npx nuxt-backend doctor\`, and \`npx nuxt-backend init --agents\` to refresh the app's
agent files and skills.

## Renamed one for one

${table(['Was', 'Now'], renamedNames(data).map(entry => [code(entry.wrong), code(entry.right)]))}

${blocks.join('\n\n')}
`
}

// ── SKILL.md regions ─────────────────────────────────────────────────────────

/** A SKILL.md with each generated region replaced by `blocks[name]`. Throws when a region is missing. */
export function fillRegions(text, blocks, file = 'SKILL.md') {
  let out = text
  for (const [name, body] of Object.entries(blocks)) {
    const start = `<!-- generated:${name} -->`
    const end = `<!-- /generated:${name} -->`
    const from = out.indexOf(start)
    const to = out.indexOf(end, from)
    if (from === -1 || to === -1) throw new Error(`${file} has no ${start} … ${end} region`)
    out = `${out.slice(0, from + start.length)}\n${body}\n${out.slice(to)}`
  }
  return out
}

/** The generated regions each skill's SKILL.md holds, by skill name. */
export function skillRegions(name) {
  return name === CORE_SKILL.name ? ['router', 'tasks', 'wrong-names', 'api'] : ['tasks']
}

/** Every generated file, by repo-relative path, with its content. */
export function outputs(data = collect()) {
  const tasks = skillTasks(data)
  const skillFile = (name, blocks) => {
    const file = `${skillDir(name)}/SKILL.md`
    return [file, fillRegions(read(file), blocks, file)]
  }
  return {
    ...Object.fromEntries([skillFile(CORE_SKILL.name, {
      'router': routerBlock(tasks),
      'tasks': compactTasksBlock(tasks.get(CORE_SKILL.name)),
      'wrong-names': wrongNamesBlock(),
      'api': apiBlock(data),
    })]),
    [`${CORE_DIR}/references/api.md`]: apiReference(data),
    [`${CORE_DIR}/references/surface.json`]: `${JSON.stringify(surfaceManifest(data), null, 2)}\n`,
    [`${CORE_DIR}/references/renames.json`]: `${JSON.stringify(renameMap(), null, 2)}\n`,
    ...Object.fromEntries(TASK_SKILLS.flatMap(skill => [
      skillFile(skill.name, { tasks: tasksBlock(tasks.get(skill.name)) }),
      ...ownsNames(skill) ? [[`${skillDir(skill.name)}/references/api.md`, skillApiReference(skill, data)]] : [],
    ])),
    [`${skillDir(UPGRADE_SKILL)}/references/upgrade.md`]: upgradeReference(data),
  }
}

/**
 * The files under skills/ that say they are generated but that `outputs`
 * no longer writes: a moved or dropped reference, which `pnpm generate`
 * deletes so the package stops shipping it.
 */
export function orphans(files = outputs()) {
  const walk = dir => readdirSync(join(root, dir)).flatMap((entry) => {
    const path = `${dir}/${entry}`
    return statSync(join(root, path)).isDirectory() ? walk(path) : [path]
  })
  return walk(SKILLS_ROOT).filter(file => !(file in files) && /\.(?:md|json)$/.test(file) && read(file).includes(GENERATED_BY))
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const files = outputs()
  const stale = Object.entries(files).filter(([file, content]) => !existsSync(join(root, file)) || read(file) !== content).map(([file]) => file)
  const dropped = orphans(files)
  if (process.argv.includes('--check')) {
    if (stale.length > 0 || dropped.length > 0) {
      console.error(`agent-guidance: stale, run \`pnpm generate\`: ${[...stale, ...dropped].join(', ')}`)
      process.exit(1)
    }
    console.log('agent-guidance: up to date')
  }
  else {
    for (const file of stale) {
      mkdirSync(dirname(join(root, file)), { recursive: true })
      writeFileSync(join(root, file), files[file])
    }
    for (const file of dropped) rmSync(join(root, file))
    const changed = [...stale, ...dropped.map(file => `${file} (deleted)`)]
    console.log(`agent-guidance: ${changed.length === 0 ? 'up to date' : `wrote ${changed.join(', ')}`}`)
  }
}
