#!/usr/bin/env node
/**
 * Writes src/pages/registry.ts: the list of the module's ready-made pages and
 * the `backend.pages` option type, from the page files in src/pages/.
 *
 * A page is one file there whose default export is a `definePage()` call,
 * with a doc comment saying what it is. Adding a page never edits a shared
 * list: add the file, then run `pnpm generate` (or this script).
 *
 *   node scripts/pages-registry.mjs          write the registry
 *   node scripts/pages-registry.mjs --check  fail when it is stale
 */
import { readdirSync, readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
const PAGES_DIR = join(root, 'src/pages')
const REGISTRY = join(PAGES_DIR, 'registry.ts')
/** The folder's own machinery, not pages. */
const NOT_PAGES = new Set(['define.ts', 'index.ts', 'registry.ts'])

/** The import name for a page file: `accept-invitation.ts` → `acceptInvitation`. */
const importName = file => file.replace(/\.ts$/, '').replace(/-(\w)/g, (_match, char) => char.toUpperCase())

/** Every page file's key and doc comment, in file-name order. */
export function readPages() {
  return readdirSync(PAGES_DIR)
    .filter(file => file.endsWith('.ts') && !NOT_PAGES.has(file))
    .sort()
    .map((file) => {
      const source = readFileSync(join(PAGES_DIR, file), 'utf8')
      const definition = source.indexOf('export default definePage({')
      const docStart = source.lastIndexOf('/**', definition)
      const docEnd = source.indexOf('*/', docStart)
      const key = source.slice(definition).match(/key: '(\w+)'/)?.[1]
      if (definition < 0 || docStart < 0 || docEnd > definition || !key) {
        throw new Error(`src/pages/${file}: expected a doc comment over \`export default definePage({ key: '…', … })\``)
      }
      const doc = source.slice(docStart + 3, docEnd).split('\n').map(line => line.replace(/^\s*\* ?/, '')).join(' ').replace(/\s+/g, ' ').trim()
      return { file, name: importName(file), key, doc }
    })
}

/** The registry's text. */
export function registryText(pages = readPages()) {
  return `// Generated by scripts/pages-registry.mjs from the page files in this folder.
// Do not edit: add a page as its own file, then run \`pnpm generate\`.
${pages.map(page => `import ${page.name} from './${page.file.replace(/\.ts$/, '')}'`).join('\n')}

/** Every ready-made page the module mounts. */
export const BACKEND_PAGE_DEFS = [
${pages.map(page => `  ${page.name},`).join('\n')}
] as const

/**
 * The ready-made pages, by key. Every page mounts at its default path; give a
 * key a path to mount the page there instead. An app page at a page's path
 * always wins: the module detects it and mounts nothing there.
 */
export interface ModulePagesOptions {
${pages.map(page => `  /** ${page.doc} */\n  ${page.key}?: string`).join('\n')}
}
`
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const next = registryText()
  const current = (() => {
    try {
      return readFileSync(REGISTRY, 'utf8')
    }
    catch {
      return ''
    }
  })()
  if (process.argv.includes('--check')) {
    if (current !== next) {
      console.error('src/pages/registry.ts is stale: run `pnpm generate`.')
      process.exit(1)
    }
    console.log('pages-registry: up to date')
  }
  else {
    writeFileSync(REGISTRY, next)
    console.log(`pages-registry: ${readPages().length} pages`)
  }
}
