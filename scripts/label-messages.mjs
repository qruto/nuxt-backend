#!/usr/bin/env node
/**
 * The package's messages for @nuxtjs/i18n and for the emails:
 *
 * - src/runtime/locales/en.json, written from the labels (src/convex/labels.ts)
 *   under `backend`. JSON rather than a module so @nuxtjs/i18n precompiles the
 *   messages at build time like an app's own: an app built with
 *   `bundle.runtimeOnly` or `dropMessageCompiler` ships no message compiler.
 *   The translations beside it (`ru.json`, `de.json`, `es.json`, `fr.json`)
 *   are written by hand, key for key.
 * - src/convex/label-translations.ts, the translations of the groups the
 *   backend renders (the emails' words), read from those files: the backend
 *   cannot read src/runtime, which does not ship as source.
 *
 * `pnpm generate` writes both; test/unit/labels.test.ts and
 * test/unit/translations.test.ts fail when they have drifted apart.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, join } from 'node:path'
import { fileURLToPath } from 'node:url'
import './lib/ts-resolve.mjs'

const { LABELS } = await import('../src/convex/labels.ts')
const { BACKEND_LABEL_GROUPS, TRANSLATED_LOCALES } = await import('../src/convex/label-format.ts')

const root = join(dirname(fileURLToPath(import.meta.url)), '..')
export const MESSAGES_FILE = 'src/runtime/locales/en.json'
export const BACKEND_TRANSLATIONS_FILE = 'src/convex/label-translations.ts'

writeFileSync(join(root, MESSAGES_FILE), `${JSON.stringify({ backend: LABELS }, null, 2)}\n`)

const translations = Object.fromEntries(TRANSLATED_LOCALES.map((locale) => {
  const { backend } = JSON.parse(readFileSync(join(root, `src/runtime/locales/${locale}.json`), 'utf8'))
  return [locale, Object.fromEntries(BACKEND_LABEL_GROUPS.map(group => [group, backend[group]]))]
}))
/** A label tree as a TypeScript literal, in the repository's style: single quotes, trailing commas. */
function literal(value, indent = '') {
  if (typeof value === 'string') return `'${value.replace(/\\/g, '\\\\').replace(/'/g, '\\\'')}'`
  const inner = `${indent}  `
  const entries = Object.entries(value).map(([key, child]) => `${inner}${/^[A-Z_$][\w$]*$/i.test(key) ? key : literal(key)}: ${literal(child, inner)},`)
  return `{\n${entries.join('\n')}\n${indent}}`
}

writeFileSync(join(root, BACKEND_TRANSLATIONS_FILE), `// Generated by scripts/label-messages.mjs from src/runtime/locales/<locale>.json: do not edit.
// The package's translations of the label groups the backend renders, by language.

import type { LabelTree } from './label-format.js'

/** The groups the backend renders (\`BACKEND_LABEL_GROUPS\`), translated, by language. */
export const LABEL_TRANSLATIONS: Record<string, LabelTree> = ${literal(translations)}
`)
console.log(`label-messages: ${MESSAGES_FILE}, ${BACKEND_TRANSLATIONS_FILE}`)
