/**
 * What the docs MCP's lookup tools answer (website/server/docs-mcp/), as
 * one JSON file: every `doctor` finding with its Diagnostics entry, every
 * env variable as the env table states it, every composable as the
 * composables table states it, and every component with its section on its
 * family page. Each record is built by the same function the reference page
 * renders, so a tool never says something the page does not. The rename map
 * `get-upgrade-guide` reads is the core skill's own `references/renames.json`.
 */
import { BACKEND_ENV } from '../../src/env-registry.ts'
import { DOCS_MCP_TOOLS } from '../../website/shared/docs-mcp.ts'
import { FINDINGS } from '../../src/findings/index.ts'
import { COMPONENT_AREAS, tagOf } from './areas.mjs'
import { findingEntry, findingIds } from './cli.mjs'
import { componentSection, familyPageOf } from './components.mjs'
import { envFacts } from './configuration.mjs'
import { composableFacts } from './nuxt.mjs'
import { code, table } from './markdown.mjs'
import { PAGES } from './paths.mjs'
import { registeredComponents, registeredComposables, summaryOf, areaTitle, tierOf } from './registry.mjs'

/** The Docs MCP page, whose tools table is generated from DOCS_MCP_TOOLS. */
export const DOCS_MCP_PAGE_FILE = 'website/content/docs/03.develop/8.agents/4.docs-mcp.md'

/** The Docs MCP page's tools table: every tool, what it takes and what it answers. */
export function docsMcpToolsTable() {
  return table(['Tool', 'Takes', 'Answers'], DOCS_MCP_TOOLS.map(tool => [code(tool.name), tool.input, tool.description]))
}

/** The file the lookup writes, which the docs MCP's tools import. */
export const DOCS_MCP_LOOKUPS_FILE = 'website/server/docs-mcp/lookups.generated.json'

/** Every lookup the docs MCP answers from, by tool. */
export function docsMcpLookups() {
  const diagnostics = Object.fromEntries(findingIds().map(id => [id, {
    capability: FINDINGS[id].capability,
    title: FINDINGS[id].title,
    url: `${PAGES.diagnostics}#${id}`,
    entry: findingEntry(id),
  }]))
  const env = Object.fromEntries(Object.keys(BACKEND_ENV).map(name => [name, {
    ...envFacts(name),
    url: `${PAGES.envVars}#every-variable`,
  }]))
  const composables = Object.fromEntries(registeredComposables().map(composable => [composable.name, {
    ...composableFacts(composable),
    url: PAGES.composables,
  }]))
  const components = Object.fromEntries(registeredComponents().map(({ name, file }) => [name, {
    tab: areaTitle(tagOf(COMPONENT_AREAS, name, 'the component')),
    tier: tierOf(name),
    summary: summaryOf(file, name),
    url: `${PAGES.components}/${familyPageOf(name)}#${name.toLowerCase()}`,
    entry: componentSection(name, file),
  }]))
  return `${JSON.stringify({
    $comment: 'What the docs MCP\'s lookup tools answer. Generated by `pnpm docs:lookups` (scripts/docs-lookups/docs-mcp.mjs) from the registries the reference pages are generated from. Do not edit: change the code it reads.',
    diagnostics,
    env,
    composables,
    components,
  }, null, 2)}\n`
}
