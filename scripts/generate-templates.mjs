#!/usr/bin/env node
/**
 * Generates `src/templates.generated.ts` — the export lists of the packaged
 * backend component's function modules and schema, parsed straight from
 * `src/convex/components/backend/*.ts`. The local-install scaffold
 * (`src/templates.ts`) builds its thin re-export files from these lists, so
 * `installation: 'local'` names exactly the functions the component ships —
 * a new mutation in `billing.ts` lands in the scaffold on the next
 * `pnpm templates:generate`, and `test/unit/templates-generated.test.ts`
 * fails until it does.
 */
import { readFileSync, writeFileSync } from 'node:fs'
import { join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'
import { parseSync } from 'oxc-parser'

const rootDir = fileURLToPath(new URL('..', import.meta.url))

/** Component source directory, relative to the repo root. */
export const COMPONENT_DIR = 'src/convex/components/backend'
/** Function modules the local scaffold re-exports (each is a package subpath: `nuxt-backend/component/<name>`). */
export const COMPONENT_MODULES = ['ai', 'billing', 'email', 'gifts', 'webhooks']
/** Where the generated file lives, relative to the repo root. */
export const OUTPUT_FILE = 'src/templates.generated.ts'

/**
 * Names of the top-level value exports of a TypeScript module — every
 * `export const X = …` (destructuring included), `export function X`,
 * `export class X`, and local `export { X }` list. Type-only exports and the
 * default export are skipped: a re-export list carries runtime values.
 *
 * @param {string} filename
 * @param {string} sourceText
 * @returns {string[]} sorted, unique
 */
export function exportedNames(filename, sourceText) {
  const { program, errors } = parseSync(filename, sourceText)
  if (errors.length > 0) {
    throw new Error(`${filename}: ${errors.map(error => error.message).join('; ')}`)
  }
  const names = new Set()
  for (const node of program.body) {
    if (node.type !== 'ExportNamedDeclaration' || node.exportKind === 'type') continue
    const { declaration } = node
    if (declaration?.type === 'VariableDeclaration') {
      for (const declarator of declaration.declarations) collectPatternNames(declarator.id, names)
    }
    else if (declaration?.type === 'FunctionDeclaration' || declaration?.type === 'ClassDeclaration') {
      if (declaration.id) names.add(declaration.id.name)
    }
    for (const specifier of node.specifiers ?? []) {
      if (specifier.exportKind === 'type') continue
      names.add(specifier.exported.name ?? specifier.exported.value)
    }
  }
  return [...names].sort()
}

/**
 * @param {any} pattern an ESTree binding pattern
 * @param {Set<string>} names
 */
function collectPatternNames(pattern, names) {
  switch (pattern.type) {
    case 'Identifier':
      names.add(pattern.name)
      break
    case 'ObjectPattern':
      for (const property of pattern.properties) {
        collectPatternNames(property.type === 'RestElement' ? property.argument : property.value, names)
      }
      break
    case 'ArrayPattern':
      for (const element of pattern.elements) if (element) collectPatternNames(element, names)
      break
    case 'AssignmentPattern':
      collectPatternNames(pattern.left, names)
      break
    case 'RestElement':
      collectPatternNames(pattern.argument, names)
      break
  }
}

/**
 * @param {string} name a module basename under {@link COMPONENT_DIR}, without extension
 * @param {string} [dir] repo root override (tests)
 */
function readModuleExports(name, dir = rootDir) {
  const file = join(dir, COMPONENT_DIR, `${name}.ts`)
  return exportedNames(file, readFileSync(file, 'utf-8'))
}

/** @param {readonly string[]} names */
function formatList(names, indent = '  ') {
  return names.map(name => `${indent}  '${name}',`).join('\n')
}

/**
 * The full text of `src/templates.generated.ts` for the component sources
 * under `dir` (defaults to this repo).
 *
 * @param {string} [dir]
 * @returns {string} the generated TypeScript source
 */
export function generate(dir = rootDir) {
  const modules = COMPONENT_MODULES.map(name => `  ${name}: [\n${formatList(readModuleExports(name, dir))}\n  ],`)
  const schema = formatList(readModuleExports('schema', dir), '')
  return [
    '/* Generated by `pnpm templates:generate` (scripts/generate-templates.mjs) — do not edit. */',
    '/**',
    ' * Top-level exports of the packaged backend component, parsed from',
    ` * ${COMPONENT_DIR}/{${COMPONENT_MODULES.join(',')},schema}.ts.`,
    ' * The local-install scaffold (src/templates.ts) re-exports exactly these names, so',
    ' * `installation: \'local\'` cannot drift from the real component —',
    ' * test/unit/templates-generated.test.ts fails while this file is stale.',
    ' */',
    '',
    '/** Every value export of each function module, sorted — `nuxt-backend/component/<name>`. */',
    'export const COMPONENT_MODULE_EXPORTS = {',
    ...modules,
    '} as const',
    '',
    '/** Every value export of the component schema, sorted — `nuxt-backend/component/schema`. */',
    'export const SCHEMA_EXPORTS = [',
    schema,
    '] as const',
    '',
  ].join('\n')
}

if (process.argv[1] && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  const output = join(rootDir, OUTPUT_FILE)
  writeFileSync(output, generate())
  console.log(`[nuxt-backend] wrote ${OUTPUT_FILE}`)
}
