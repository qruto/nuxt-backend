/**
 * The one brand. `appConfig.backend.brand` is where an app writes its name,
 * logo and postal address; the pages read it at runtime, and the backend,
 * which never reads app config, needs the same three for its emails and
 * passkey prompts. The module carries them across as `brand.generated.ts`
 * in the functions directory, beside `paths.generated.ts`: no env var, and
 * the brand deploys with the code that reads it. The scaffold passes the
 * file's `brand` to `setupEmail`, whose own `brand` option stays an
 * override for the emails alone.
 *
 * This file reads the brand out of the app's `app.config` files and renders
 * the generated file; src/brand-sync.ts writes and checks it.
 */
import { existsSync, readFileSync } from 'node:fs'
import { join } from 'node:path'
import { type Magicast, type Node, parse } from './source-text'

/** The generated file's name, in the functions directory. */
export const BRAND_FILE = 'brand.generated.ts'

/** The brand the backend reads: each field the app config sets. */
export interface BackendBrand {
  name?: string
  logo?: string
  address?: string
}

/** The fields the file carries, in its order. */
export const BRAND_KEYS = ['name', 'logo', 'address'] as const satisfies ReadonlyArray<keyof BackendBrand>

/** A value as a single-quoted TypeScript string, which the app's linter accepts. */
function quoted(value: string): string {
  return `'${JSON.stringify(value).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, '\\\'')}'`
}

/** The file's text for a brand. Deterministic: the same brand writes the same bytes. */
export function renderBrandFile(brand: BackendBrand): string {
  const lines = BRAND_KEYS.flatMap(key => brand[key] === undefined ? [] : [`  ${key}: ${quoted(brand[key]!)},`])
  return [
    '/* Generated by nuxt-backend from app.config (`backend.brand`) — do not edit. */',
    '// The Nuxt module rewrites this file whenever app.config changes the brand, and',
    '// the backend reads it: email.ts passes `brand` on. Commit it.',
    lines.length === 0 ? 'export const brand: { name?: string, logo?: string, address?: string } = {}' : 'export const brand: { name?: string, logo?: string, address?: string } = {',
    ...(lines.length === 0 ? [] : [...lines, '}']),
    '',
  ].join('\n')
}

/** A string literal's value, or a template literal's without placeholders; `undefined` for anything else. */
function literal(node: Node | undefined): string | undefined {
  if (!node) return undefined
  if (node.type === 'StringLiteral' && typeof node.value === 'string') return node.value
  if (node.type === 'TemplateLiteral' && Array.isArray(node.expressions) && node.expressions.length === 0) {
    const quasi = (node.quasis as Array<{ value?: { cooked?: string } }>)[0]
    return quasi?.value?.cooked
  }
  return undefined
}

/** The value a property of an object literal holds, by its key. */
function property(object: Node | undefined, key: string): Node | undefined {
  if (object?.type !== 'ObjectExpression') return undefined
  const found = (object.properties as Node[]).find((entry) => {
    if (entry.type !== 'ObjectProperty') return false
    const name = entry.key as Node
    return (name.type === 'Identifier' && name.name === key) || (name.type === 'StringLiteral' && name.value === key)
  })
  return found?.value as Node | undefined
}

/** The object an `app.config` file exports: `defineAppConfig({ … })`, or a plain object. */
function exportedObject(program: Node): Node | undefined {
  const declaration = (program.body as Node[]).find(statement => statement.type === 'ExportDefaultDeclaration')?.declaration as Node | undefined
  if (!declaration) return undefined
  if (declaration.type === 'ObjectExpression') return declaration
  if (declaration.type === 'CallExpression') return (declaration.arguments as Node[])[0]
  if (declaration.type === 'TSAsExpression' || declaration.type === 'TSSatisfiesExpression') return exportedObject({ type: 'Program', body: [{ type: 'ExportDefaultDeclaration', declaration: declaration.expression }] })
  return undefined
}

/**
 * The brand one `app.config` file writes as literals: what the backend can
 * carry without running the app. A field written as an expression is left
 * out (the pages still read it at runtime).
 */
export function brandOfAppConfig(magicast: Magicast, text: string): BackendBrand {
  const program = parse(magicast, text)
  if (typeof program === 'string') return {}
  const brand = property(property(exportedObject((program as { program?: Node }).program ?? program), 'backend'), 'brand')
  const read: BackendBrand = {}
  for (const key of BRAND_KEYS) {
    const value = literal(property(brand, key))?.trim()
    if (value) read[key] = value
  }
  return read
}

/** The extensions Nuxt reads an `app.config` file with. */
const APP_CONFIG_FILES = ['app.config.ts', 'app.config.mts', 'app.config.js', 'app.config.mjs']

/**
 * The brand of an app and the layers it extends, from their `app.config`
 * files: the app's own field wins over a layer's, as Nuxt merges app config.
 * `srcDirs` lists the app's source directory first.
 */
export async function readAppBrand(srcDirs: readonly string[]): Promise<BackendBrand> {
  const magicast = await import('magicast')
  const brand: BackendBrand = {}
  for (const dir of srcDirs) {
    const file = APP_CONFIG_FILES.map(name => join(dir, name)).find(existsSync)
    if (!file) continue
    const layer = brandOfAppConfig(magicast, readFileSync(file, 'utf-8'))
    for (const key of BRAND_KEYS) {
      if (brand[key] === undefined && layer[key] !== undefined) brand[key] = layer[key]
    }
  }
  return brand
}

/** What a loaded nuxt.config says of its layers: each one's source directory, the app's first. */
interface LayeredConfig {
  rootDir?: string
  srcDir?: string
  _layers?: Array<{ cwd?: string, config?: { rootDir?: string, srcDir?: string } }>
}

/** The source directories whose `app.config` files hold the brand, the app's own first. */
export function brandSourceDirs(config: LayeredConfig): string[] {
  const dirs = (config._layers ?? []).flatMap((layer) => {
    const root = layer.config?.rootDir ?? layer.cwd
    const src = layer.config?.srcDir
    return [...(src ? [src.startsWith('/') || !root ? src : join(root, src)] : []), ...(root ? [join(root, 'app'), root] : [])]
  })
  const own = [config.srcDir, ...(config.rootDir ? [join(config.rootDir, 'app'), config.rootDir] : [])].filter((dir): dir is string => Boolean(dir))
  return [...new Set([...own, ...dirs])]
}

/** The brand of a loaded nuxt.config's app and layers; `null` when it reads none. */
export async function appBrandOf(config: LayeredConfig | null): Promise<BackendBrand | null> {
  if (!config) return null
  try {
    return await readAppBrand(brandSourceDirs(config))
  }
  catch {
    return null
  }
}
