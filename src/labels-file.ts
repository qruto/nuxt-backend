/**
 * The labels an app sets in app config, carried to the backend.
 * `appConfig.backend.labels` is where an app rewords the package's copy and
 * gives its own notification kinds their words; the pages read it at
 * runtime, and the backend, which never reads app config, words emails,
 * notifications and push with the same labels. The module carries them
 * across as `labels.generated.ts` in the functions directory, beside
 * `brand.generated.ts`, and the scaffold's email.ts passes the file's
 * `labels` to `setupEmail`. So copy is written once, in app config.
 *
 * This file reads the labels out of the app's `app.config` files without
 * running them and renders the generated file; src/labels-sync.ts writes
 * and checks it.
 */
import { existsSync, readFileSync, statSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { APP_CONFIG_FILES, brandSourceDirs, exportedObject, literal, property, quoted } from './brand-file'
import type { LabelTree } from './convex/label-format'
import { type Magicast, type Node, parse } from './source-text'

/** The generated file's name, in the functions directory. */
export const LABELS_FILE = 'labels.generated.ts'

/** A key as an object literal writes it: bare when it is an identifier, else quoted. */
function keyOf(key: string): string {
  return /^[A-Z_$][\w$]*$/i.test(key) ? key : quoted(key)
}

/** A label tree's lines, indented under its parent. */
function treeLines(tree: LabelTree, indent: string): string[] {
  return Object.entries(tree).flatMap(([key, value]) => typeof value === 'string'
    ? [`${indent}${keyOf(key)}: ${quoted(value)},`]
    : [`${indent}${keyOf(key)}: {`, ...treeLines(value, `${indent}  `), `${indent}},`])
}

/** The file's text for the labels. Deterministic: the same labels write the same bytes. */
export function renderLabelsFile(labels: LabelTree): string {
  const lines = treeLines(labels, '  ')
  return [
    '/* Generated by nuxt-backend from app.config (`backend.labels`) — do not edit. */',
    '// The Nuxt module rewrites this file whenever app.config changes a label, and the',
    '// backend reads it: email.ts passes `labels` on, so emails and notifications say what the pages say. Commit it.',
    lines.length === 0 ? 'export const labels = {}' : 'export const labels = {',
    ...(lines.length === 0 ? [] : [...lines, '}']),
    '',
  ].join('\n')
}

/** How many imports deep a label is followed: app.config → a copy file → a file it imports, and no further. */
const IMPORT_DEPTH = 3

/** The extensions a relative import is tried with, the way the app's bundler resolves it. */
const MODULE_FILES = ['', '.ts', '.mts', '.js', '.mjs', '/index.ts', '/index.js']

/** One parsed module: its file and its top-level statements. */
interface ModuleScope {
  file: string
  body: Node[]
  depth: number
}

/** A node with the TypeScript wrappers that leave its value as it is (`as const`, `satisfies`, `!`, parentheses) taken off. */
function unwrapped(node: Node | undefined): Node | undefined {
  let current = node
  while (current && ['TSAsExpression', 'TSSatisfiesExpression', 'TSNonNullExpression', 'ParenthesizedExpression', 'TSTypeAssertion'].includes(current.type)) current = current.expression as Node
  return current
}

/** The value a top-level `const` of the module holds, exported or not. */
function constOf(scope: ModuleScope, name: string): Node | undefined {
  for (const statement of scope.body) {
    const declaration = statement.type === 'ExportNamedDeclaration' ? statement.declaration as Node | undefined : statement
    if (declaration?.type !== 'VariableDeclaration' || declaration.kind !== 'const') continue
    const found = (declaration.declarations as Node[]).find(entry => (entry.id as Node).type === 'Identifier' && (entry.id as Node).name === name)
    if (found) return found.init as Node | undefined
  }
  return undefined
}

/** The module a relative specifier names, parsed; `undefined` for a package, a file that is not there, or one past the depth. */
function importedScope(magicast: Magicast, scope: ModuleScope, specifier: string): ModuleScope | undefined {
  if (!specifier.startsWith('.') || scope.depth >= IMPORT_DEPTH) return undefined
  const base = resolve(dirname(scope.file), specifier)
  const file = MODULE_FILES.map(extension => `${base}${extension}`).find(candidate => /\.[mc]?[jt]s$/.test(candidate) && statSync(candidate, { throwIfNoEntry: false })?.isFile())
  if (!file) return undefined
  const program = parse(magicast, readFileSync(file, 'utf-8'))
  if (typeof program === 'string') return undefined
  return { file, body: programBody(program), depth: scope.depth + 1 }
}

/** The import of the module that binds `name`, with its specifier; type-only imports carry no value. */
function importOf(scope: ModuleScope, name: string): { source: string, specifier: Node } | undefined {
  for (const statement of scope.body) {
    if (statement.type !== 'ImportDeclaration' || statement.importKind === 'type') continue
    const specifier = (statement.specifiers as Node[]).find(entry => (entry.local as Node).name === name)
    if (specifier) return { source: (statement.source as Node).value as string, specifier }
  }
  return undefined
}

/** What an import binds in the file it names: its default export, or the `const` it names. */
function importedValue(magicast: Magicast, scope: ModuleScope, { source, specifier }: { source: string, specifier: Node }): { node: Node, scope: ModuleScope } | undefined {
  const target = importedScope(magicast, scope, source)
  if (!target) return undefined
  let node: Node | undefined
  if (specifier.type === 'ImportDefaultSpecifier') node = target.body.find(entry => entry.type === 'ExportDefaultDeclaration')?.declaration as Node | undefined
  else if (specifier.type === 'ImportSpecifier') {
    const imported = specifier.imported as Node
    node = constOf(target, (imported.type === 'Identifier' ? imported.name : imported.value) as string)
  }
  return node ? { node, scope: target } : undefined
}

/** The value a name of the module stands for: a `const` of its own, or a named or default import from a relative file. */
function binding(magicast: Magicast, scope: ModuleScope, name: string): { node: Node, scope: ModuleScope } | undefined {
  const own = constOf(scope, name)
  if (own) return { node: own, scope }
  const imported = importOf(scope, name)
  return imported ? importedValue(magicast, scope, imported) : undefined
}

/** Keys that would reach an object's prototype when written: never a label's. */
const UNSAFE_KEYS = new Set(['__proto__', 'constructor', 'prototype'])

/** A property's key as text; `undefined` for a computed one, and for one that would reach the tree's prototype. */
function keyName(entry: Node): string | undefined {
  if (entry.computed) return undefined
  const key = entry.key as Node
  const name = key.type === 'Identifier' ? key.name as string : key.type === 'StringLiteral' ? key.value as string : undefined
  return name === undefined || UNSAFE_KEYS.has(name) ? undefined : name
}

/** What one entry of an object literal adds to the tree: a spread's labels, or one key's label or tree (an empty one adds nothing). */
function entryLabels(magicast: Magicast, entry: Node, scope: ModuleScope, seen: ReadonlySet<Node>): LabelTree {
  if (entry.type === 'SpreadElement') {
    const spread = labelValue(magicast, entry.argument as Node, scope, seen)
    return spread && typeof spread === 'object' ? spread : {}
  }
  const key = entry.type === 'ObjectProperty' ? keyName(entry) : undefined
  if (key === undefined) return {}
  const read = labelValue(magicast, entry.value as Node, scope, seen)
  return read !== undefined && (typeof read === 'string' || Object.keys(read).length > 0) ? { [key]: read } : {}
}

/**
 * A label or a tree of them, as the module can read it without running the
 * app: string literals, objects of them, a `const` of the same file, and a
 * named or default import of a relative file (a copy file app.config
 * imports). Anything else, a call or a computed key, is left out; the
 * pages still read it at runtime.
 */
function labelValue(magicast: Magicast, node: Node | undefined, scope: ModuleScope, seen: ReadonlySet<Node>): string | LabelTree | undefined {
  const value = unwrapped(node)
  if (!value || seen.has(value)) return undefined
  const text = literal(value)
  if (text !== undefined) return text
  const inner = new Set([...seen, value])
  if (value.type === 'Identifier') {
    const bound = binding(magicast, scope, value.name as string)
    return bound ? labelValue(magicast, bound.node, bound.scope, inner) : undefined
  }
  if (value.type !== 'ObjectExpression') return undefined
  return Object.assign({}, ...(value.properties as Node[]).map(entry => entryLabels(magicast, entry, scope, inner))) as LabelTree
}

/** A parsed file's top-level statements. */
function programBody(program: Node): Node[] {
  return ((program as { program?: Node }).program ?? program).body as Node[]
}

/**
 * The labels one `app.config` file sets, read without running the app (see
 * `labelValue`): empty for a file that does not parse or sets none.
 */
export function labelsOfAppConfig(magicast: Magicast, text: string, file: string): LabelTree {
  const program = parse(magicast, text)
  if (typeof program === 'string') return {}
  const scope: ModuleScope = { file, body: programBody(program), depth: 0 }
  const backend = unwrapped(property(exportedObject((program as { program?: Node }).program ?? program), 'backend'))
  const read = labelValue(magicast, property(backend, 'labels'), scope, new Set())
  return read && typeof read === 'object' ? read : {}
}

/** `layer` under `into`, key by key: what `into` sets already stays, as Nuxt merges app config. A key that would reach the prototype is skipped. */
function mergeUnder(into: LabelTree, layer: LabelTree): void {
  for (const [key, value] of Object.entries(layer)) {
    if (UNSAFE_KEYS.has(key)) continue
    const own = Object.hasOwn(into, key) ? into[key] : undefined
    if (own === undefined) into[key] = typeof value === 'string' ? value : structuredClone(value)
    else if (typeof own === 'object' && typeof value === 'object') mergeUnder(own, value)
  }
}

/**
 * The labels of an app and the layers it extends, from their `app.config`
 * files: the app's own label wins over a layer's, key by key. `srcDirs`
 * lists the app's source directory first.
 */
export async function readAppLabels(srcDirs: readonly string[]): Promise<LabelTree> {
  const magicast = await import('magicast')
  const labels: LabelTree = {}
  for (const dir of srcDirs) {
    const file = APP_CONFIG_FILES.map(name => join(dir, name)).find(existsSync)
    if (file) mergeUnder(labels, labelsOfAppConfig(magicast, readFileSync(file, 'utf-8'), file))
  }
  return labels
}

/** The labels of a loaded nuxt.config's app and layers; `null` when they cannot be read. */
export async function appLabelsOf(config: Parameters<typeof brandSourceDirs>[0] | null): Promise<LabelTree | null> {
  if (!config) return null
  try {
    return await readAppLabels(brandSourceDirs(config))
  }
  catch {
    return null
  }
}
