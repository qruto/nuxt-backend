import { addTemplate, hasNuxtModule } from '@nuxt/kit'
import type { Nuxt } from '@nuxt/schema'
import { logger } from './logger'

// The theme bridge: the packaged components adopt the theme an app already
// has. With @nuxt/ui, the neutrals, the edge and the card radius map onto
// Nuxt UI's own, while the signals stay the package's (wide-gamut, see
// tokens.css); with @nuxtjs/color-mode (which @nuxt/ui installs), the components
// follow the class it puts on <html>, not the OS preference. One generated
// stylesheet, in the same cascade layer as the package's own and right after
// it, so an app's override still wins without specificity.

/**
 * Every root the token layer themes. tokens.css declares the same list;
 * test/unit/theme-bridge.test.ts holds the two together.
 *
 * @internal
 */
export const TOKEN_ROOTS = [
  '[data-auth=\'form\']',
  '[data-auth=\'page\']',
  '[data-invitation]',
  '[data-consent]',
  '[data-gift=\'banner\']',
  '[data-credits=\'banner\']',
  '[data-history=\'root\']',
  '[data-usage=\'root\']',
  '[data-pricing=\'table\']',
  '[data-pricing=\'page\']',
  '[data-settings=\'root\']',
  '[data-settings=\'page\']',
  '[data-profile=\'root\']',
  '[data-profile=\'page\']',
  '[data-security=\'root\']',
  '[data-security=\'page\']',
] as const

/**
 * The `--bk-*` tokens on Nuxt UI's: the neutrals, the edge and the card
 * radius, the variables Nuxt UI documents for an app to theme (an app
 * restyles them the Nuxt UI way, in its own CSS). The signals and the text on
 * the accent stay the package's own wide-gamut colours, `--bk-ink` keeps
 * inheriting the text colour Nuxt UI gives the page, and controls stay pills
 * (`--bk-radius-control`). The card radius is Nuxt UI's `rounded-lg`, its
 * cards'.
 *
 * @internal
 */
export const NUXT_UI_TOKENS: Readonly<Record<string, string>> = {
  '--bk-muted': 'var(--ui-text-muted)',
  '--bk-edge': 'var(--ui-border)',
  '--bk-surface': 'var(--ui-bg-muted)',
  '--bk-radius': 'calc(var(--ui-radius) * 2)',
}

/** @internal */
export interface ThemeBridge {
  /** Map the tokens onto @nuxt/ui's. */
  nuxtUi: boolean
  /** The class names @nuxtjs/color-mode puts on <html>, or `false` without it. */
  colorMode: { dark: string, light: string } | false
}

const roots = `:where(${TOKEN_ROOTS.join(', ')})`

/**
 * The bridge stylesheet, or `''` when the app has nothing to bridge to.
 *
 * @internal
 */
export function themeBridgeCss(bridge: ThemeBridge): string {
  const rules: string[] = []
  if (bridge.nuxtUi) {
    const declarations = Object.entries(NUXT_UI_TOKENS).map(([token, value]) => `    ${token}: ${value};`)
    rules.push(`  ${roots} {\n${declarations.join('\n')}\n  }`)
  }
  if (bridge.colorMode) {
    // light-dark() in the token defaults resolves against color-scheme, which
    // color-mode never sets: without these, a dark page under a light OS
    // keeps the light values.
    rules.push(`  :where(html.${bridge.colorMode.dark}) ${roots} {\n    color-scheme: dark;\n  }`)
    rules.push(`  :where(html.${bridge.colorMode.light}) ${roots} {\n    color-scheme: light;\n  }`)
  }
  if (rules.length === 0) return ''
  // The layer order statement again, as ui.css declares it: wherever this file
  // ends up, `components` never becomes the first layer declared.
  return `/* Generated by nuxt-backend: the packaged components on the app's theme. */\n@layer theme, base, components, utilities;\n\n@layer components.backend {\n${rules.join('\n\n')}\n}\n`
}

/** A class-name affix @nuxtjs/color-mode may be configured with. */
const CLASS_AFFIX = /^[\w-]*$/

/**
 * What the app has installed to bridge to: read once every module is in,
 * because an app may list @nuxt/ui after this module.
 *
 * @internal
 */
export function detectThemeBridge(nuxt: Nuxt): ThemeBridge {
  let colorMode: ThemeBridge['colorMode'] = false
  if (hasNuxtModule('@nuxtjs/color-mode', nuxt)) {
    const options = (nuxt.options as { colorMode?: { classPrefix?: string, classSuffix?: string } }).colorMode
    const prefix = options?.classPrefix ?? ''
    const suffix = options?.classSuffix ?? ''
    if (CLASS_AFFIX.test(prefix) && CLASS_AFFIX.test(suffix)) {
      colorMode = { dark: `${prefix}dark${suffix}`, light: `${prefix}light${suffix}` }
    }
    else {
      logger.warn(`The packaged components can't follow @nuxtjs/color-mode: its class affixes (${JSON.stringify(prefix)}, ${JSON.stringify(suffix)}) aren't plain class names. Set \`color-scheme\` on the page yourself.`)
    }
  }
  return { nuxtUi: hasNuxtModule('@nuxt/ui', nuxt), colorMode }
}

/**
 * Add the bridge stylesheet right after `uiCss` once every module is in.
 * Nothing is added for an app with neither module.
 */
export function registerThemeBridge(nuxt: Nuxt, uiCss: string): void {
  nuxt.hook('modules:done', () => {
    const contents = themeBridgeCss(detectThemeBridge(nuxt))
    if (!contents) return
    const { dst } = addTemplate({ filename: 'nuxt-backend/theme-bridge.css', getContents: () => contents, write: true })
    const at = nuxt.options.css.indexOf(uiCss)
    if (at < 0) nuxt.options.css.push(dst)
    else nuxt.options.css.splice(at + 1, 0, dst)
  })
}
