/**
 * The one path source. nuxt.config is the only place an app writes a path
 * (`backend.authRoute`, `backend.pages`); the backend needs some of them too
 * (the auth routes' base path, and the pages its emails link to). The module
 * carries them across as `paths.generated.ts` in the functions directory: no
 * env var, and the paths deploy with the code that reads them. The scaffold
 * passes the file's `paths` to `defineBackendAuthConfig`, `setupAuth` and
 * `setupAccount`, and a waitlist passes them to `setupWaitlist`. This file renders and reads it; src/paths-sync.ts writes
 * and checks it.
 */
import { defu } from 'defu'
import { DEFAULT_AUTH_ROUTE } from './convex/constants'
import { BACKEND_PATH_KEYS, type BackendPaths } from './convex/paths'
import { normalizePagePath, resolvePagePath, type ModulePagesOptions } from './pages'

/** The generated file's name, in the functions directory. */
export const PATHS_FILE = 'paths.generated.ts'

/** What of nuxt.config's `backend` key the paths come from. */
export interface PathsSource {
  authRoute?: string
  pages?: ModulePagesOptions
}

/**
 * The paths source nuxt.config gives the module: the options written inline
 * in `modules` (`['nuxt-backend', { … }]`), over its `backend` key, merged
 * as Nuxt merges them. What `doctor` and `doctor --fix` read, so they agree
 * with the file the module writes.
 */
export function pathsSourceOf(config: { backend?: PathsSource, modules?: unknown[] }): PathsSource {
  const inline = (config.modules ?? []).flatMap(entry => Array.isArray(entry) && entry[0] === 'nuxt-backend' && entry[1] && typeof entry[1] === 'object' ? [entry[1] as PathsSource] : [])
  return defu({}, ...inline, config.backend ?? {})
}

/** The page key each path follows; `authRoute` follows the option of that name. */
const PAGE_OF = {
  acceptInvitation: 'acceptInvitation',
  keepAccount: 'keepAccount',
  security: 'security',
  waitlist: 'waitlist',
  login: 'login',
  unsubscribe: 'unsubscribe',
  report: 'report',
  settings: 'settings',
  privacy: 'privacy',
} as const satisfies Record<Exclude<keyof BackendPaths, 'authRoute'>, string>

/** Where nuxt.config writes each path, for a message: `backend.authRoute`, `backend.pages.security`. */
export function pathOption(key: keyof BackendPaths): string {
  return key === 'authRoute' ? 'backend.authRoute' : `backend.pages.${PAGE_OF[key]}`
}

/**
 * The paths nuxt.config's `backend` key declares, each page at its default
 * path unless moved. The auth route is read as the proxy mounts it: a
 * missing leading slash added, trailing ones dropped.
 */
export function backendPathsOf(source: PathsSource | undefined): BackendPaths {
  const route = typeof source?.authRoute === 'string' && source.authRoute.trim() ? source.authRoute.trim() : DEFAULT_AUTH_ROUTE
  return {
    authRoute: normalizePagePath(route),
    acceptInvitation: resolvePagePath(source?.pages, PAGE_OF.acceptInvitation),
    keepAccount: resolvePagePath(source?.pages, PAGE_OF.keepAccount),
    security: resolvePagePath(source?.pages, PAGE_OF.security),
    waitlist: resolvePagePath(source?.pages, PAGE_OF.waitlist),
    login: resolvePagePath(source?.pages, PAGE_OF.login),
    unsubscribe: resolvePagePath(source?.pages, PAGE_OF.unsubscribe),
    report: resolvePagePath(source?.pages, PAGE_OF.report),
    settings: resolvePagePath(source?.pages, PAGE_OF.settings),
    privacy: resolvePagePath(source?.pages, PAGE_OF.privacy),
  }
}

/** A path as a single-quoted TypeScript string, which the app's linter accepts: JSON's escapes, with `'` escaped instead of `"`. */
function quotedPath(path: string): string {
  return `'${JSON.stringify(path).slice(1, -1).replace(/\\"/g, '"').replace(/'/g, '\\\'')}'`
}

/** A single-quoted string's content as {@link quotedPath} writes it, read back; undefined when it does not read. */
function unquotedPath(content: string): string | undefined {
  try {
    return JSON.parse(`"${content.replace(/\\'/g, '\'').replace(/"/g, '\\"')}"`) as string
  }
  catch {
    return undefined
  }
}

/** The file's text for a set of paths. Deterministic: the same paths write the same bytes. */
export function renderPathsFile(paths: BackendPaths): string {
  const lines = BACKEND_PATH_KEYS.map(key => `  ${key}: ${quotedPath(paths[key])},`)
  return [
    '/* Generated by nuxt-backend from nuxt.config (`backend.authRoute`, `backend.pages`) — do not edit. */',
    '// The Nuxt module rewrites this file whenever nuxt.config moves a path, and the',
    '// backend reads it: auth.config.ts, auth.ts, account.ts, email.ts, billing.ts, waitlist.ts and access.ts pass `paths` on. Commit it.',
    'export const paths = {',
    ...lines,
    '} as const',
    '',
  ].join('\n')
}

/** The paths a generated file holds, read back line by line; a key it does not name is left out. */
export function parsePathsFile(text: string): Partial<BackendPaths> {
  const paths: Partial<BackendPaths> = {}
  for (const key of BACKEND_PATH_KEYS) {
    // fallow-ignore-next-line security-sink -- the key is one of BACKEND_PATH_KEYS, fixed lower-camel identifiers, never input; the pattern is linear; verified 2026-10-28
    const content = new RegExp(`^\\s*${key}:\\s*'((?:[^'\\\\\\n]|\\\\.)*)'`, 'm').exec(text)?.[1]
    const value = content === undefined ? undefined : unquotedPath(content)
    if (value !== undefined) paths[key] = value
  }
  return paths
}
